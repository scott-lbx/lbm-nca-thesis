"""
config_utils/constants.py

LBM 模擬的物理常數與穩定性閾值。

所有模組應從此處 import 常數，禁止在其他模組重複定義。
"""

import math

# ── 格子玻爾茲曼聲速 ──────────────────────────────────────────────────────
CS2 = 1.0 / 3.0
CS = math.sqrt(CS2)  # ≈ 0.5774 lu/step (lattice sound speed)

# ── 入口馬赫數上限 ────────────────────────────────────────────────────────
MA_LIMIT = 0.17  # 入口均值 Ma 上限（對應 u ≈ 0.098 lu/step）

# ── LBM 鬆弛時間下限 ──────────────────────────────────────────────────────
# MRT-LES solver 的 Smagorinsky 渦黏修正保證 tau_eff = tau_0 + tau_eddy >= tau_0，
# 提供額外穩定裕度，因此 tau_0 可安全逼近 0.5（BGK 需 >=0.52，MRT-LES 可放寬）。
TAU_MIN = 0.508  # tau 下限（對應 nu_lb_min ≈ 0.00267）

# ── 速度入口安全係數 ──────────────────────────────────────────────────────
# 2D 都市流場的局部加速可達 inlet 的 5-6x（角落效應 + 渦旋暫態）
# 需要足夠保守避免 MaxV > 0.25 穩定性閾值
MA_SAFETY_FACTOR = 3.0

# ── 阻塞率感知參數 ────────────────────────────────────────────────────────
MIN_OPEN = 0.20  # 最小開放比（防極端阻塞時分母趨近 0）

# ── Reynolds 數上限 ───────────────────────────────────────────────────────
RE_MAX = 1200  # Re 上限：超過此值在 2D LBM 都市場景數值不穩定
